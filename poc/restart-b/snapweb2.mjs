import { chromium } from 'playwright'
const b = await chromium.launch()
const p = await b.newPage({ viewport: { width: 1400, height: 1000 } })
await p.goto('http://127.0.0.1:8790/?token='+process.argv[2])
await p.waitForTimeout(5000)
await p.getByText('RESTART please').first().click()
await p.waitForTimeout(3000)
const box = p.locator('textarea, [contenteditable="true"]').first()
await box.click(); await box.fill('after restart')
await p.getByRole('button', { name: 'Send message' }).click()
await p.waitForTimeout(12000)
await p.screenshot({ path: '/workspace/work/snapb/wfollow.png' })
console.log(p.url()); console.log((await p.locator('main, body').first().innerText()).slice(-400))
await b.close()
